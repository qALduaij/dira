export type Entity = {
  name: string;
  kind: string;
  confidence: number;
  track_id?: string;
};
export type Event = {
  id: string;
  channel_id: string;
  start: string;
  end: string;
  transcript: string;
  translation: string;
  ocr: string;
  visual: string;
  speaker?: string;
  confidence: number | null;
  language: string;
  simulated: boolean;
  source: string;
  entities: Entity[];
};
export type Channel = {
  id: string;
  name: string;
  name_ar: string;
  short: string;
  region: string;
  color: string;
  category: string;
  status: string;
  playback_url: string;
  asr_lag_seconds?: number | null;
  asr_resets?: number;
  asr_skipped_seconds?: number;
  asr_degraded?: boolean;
  asr_last_reset_cause?: string | null;
};
export type Alert = {
  id: string;
  tdo_id: string | null; // null for system-health alerts
  channel_id: string;
  timestamp: string;
  rule_name: string;
  severity: string;
  detail: string;
  kind: string;
  acknowledged: boolean;
  simulated: boolean;
};
export type Brief = {
  id: string;
  title: string;
  content: string;
  evidence_ids: string[];
  input_evidence_ids?: string[];
  coverage?: {
    sampled_observations: number;
    total_observations: number;
    window_start: string;
    window_end: string;
    sampled_channels: number;
  };
  created_at: string;
  mode: string;
  kind: string;
  simulated: boolean;
  error?: string;
};
export type Rule = {
  id: string;
  name: string;
  pattern: string;
  kind: string;
  severity: string;
  enabled: boolean;
  channel_id?: string;
};
export type Metrics = {
  mode: string;
  paused: boolean;
  evidence: number;
  pending: number;
  hot_vectors: number;
  latency_p95_ms: number;
  asr_lag_max_seconds?: number | null;
  asr_max_lag?: number;
  processed: number;
  uptime_seconds: number;
  device: string;
  encoder: string;
  warm_status: string;
  llm: string;
  cloud_auto_briefs?: boolean;
  active_alerts?: number;
  disk_free_gb?: number;
  disk_guard_active?: boolean;
  hot_capacity?: number;
  hot_horizon_seconds?: number;
  ws_resyncs: number;
  regex_timeouts: number;
  jobs_pending: number;
  history: { time: string; events: number; latency_ms: number }[];
};
export type Snapshot = {
  channels: Channel[];
  events: Event[];
  alerts: Alert[];
  briefs: Brief[];
  rules: Rule[];
  metrics: Metrics;
  sequence: number;
};
